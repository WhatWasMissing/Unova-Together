"""Compile the private ARM context payload and regenerate its source header.

Profile bytes come from a private supported-ROM capture and are short function
fingerprints, not a bundled ROM. Requires the locally installed ARM toolchain.
"""
from pathlib import Path
import argparse
import hashlib
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'melonDS-source-1.1/src/frontend/qt_sdl/native/CoopContext.c'
HEADER = SOURCE.parent.parent / 'NativeCoopPayload.h'
ADDRESSES = (0x020169A8, 0x02016AD8, 0x0201735C, 0x0201FDF8,
             0x02039D9C, 0x02039E2C, 0x02161844, 0x020425EC, 0x02042860,
             0x02161858, 0x02161884, 0x02161888,
             0x02161AD8, 0x02161B4C, 0x02161B80, 0x02161BBC,
             0x02161BE8, 0x02161C1C, 0x02161C40, 0x02161C64,
             0x0201FF08, 0x0201FD34, 0x0201FD6C,
             0x02040440, 0x02017C60, 0x02017C84, 0x0201848C, 0x020200AC,
             0x020405F8, 0x02040654, 0x0203FFC4, 0x02040474,
             0x020429F8, 0x02041A30, 0x02041C00, 0x02016AEC,
             0x02016CB4, 0x02016EDC, 0x02168BAC, 0x0216911C,
             0x02016E00, 0x02040C20, 0x02040C64, 0x02017D18, 0x0201CCF8,
             0x02016D68, 0x020174AC, 0x021690A0, 0x021686CC, 0x02168814,
             0x0204230C, 0x020427B8, 0x0201840C, 0x02042A6C)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('capture', type=Path)
    parser.add_argument('--toolchain', type=Path, default=Path('C:/SysGCC/arm-eabi/bin'))
    args = parser.parse_args()
    capture = args.capture.read_bytes()
    if len(capture) != 0x400000:
        raise ValueError('Expected a 4 MiB main RAM capture')
    output = ROOT / 'research/co-op'
    elf, binary = output / 'CoopContext.elf', output / 'CoopContext.bin'
    tool = lambda name: str(args.toolchain / f'arm-none-eabi-{name}.exe')
    subprocess.run([tool('gcc'), '-mcpu=arm946e-s', '-mthumb', '-Os',
                    '-ffreestanding', '-fno-builtin', '-fno-unwind-tables',
                    '-fno-asynchronous-unwind-tables', '-nostdlib',
                    '-Wl,-Ttext=0x03003000', '-Wl,-e,PokePlayPrepareCoopContext',
                    str(SOURCE), '-o', str(elf)], check=True)
    subprocess.run([tool('objcopy'), '-O', 'binary', '-j', '.text', str(elf), str(binary)], check=True)
    symbols = subprocess.check_output([tool('nm'), '-n', str(elf)], text=True)
    offsets = {}
    for line in symbols.splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[2].startswith('PokePlay'):
            offsets[fields[2]] = int(fields[0], 16) - 0x03003000
    code = binary.read_bytes()
    rows = [','.join(f'0x{byte:02x}' for byte in code[i:i+16]) for i in range(0, len(code), 16)]
    fingerprints = []
    for address in ADDRESSES:
        data = capture[address-0x02000000:address-0x02000000+8]
        fingerprints.append('    {0x%x, {%s}},' % (address, ','.join(f'0x{b:02x}' for b in data)))
    text = ('#pragma once\n#include <array>\n#include <cstdint>\n'
            '// Generated by tools/build_coop_payload.py from native/CoopContext.c.\n'
            f'// Source SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}\n'
            'namespace CoopNativePayload {\n'
            f'inline constexpr std::array<unsigned char,{len(code)}> Code={{\n    '
            + ',\n    '.join(rows) + ',\n};\n'
            + ''.join(f'inline constexpr std::uint32_t {name}Offset=0x{offset:x};\n'
                      for name, offset in offsets.items())
            + 'struct Fingerprint {std::uint32_t address;std::array<unsigned char,8> bytes;};\n'
            + f'inline constexpr std::array<Fingerprint,{len(ADDRESSES)}> Profile={{{{\n'
            + '\n'.join(fingerprints) + '\n}};\n}\n')
    HEADER.write_text(text, encoding='utf-8')
    print(f'Generated {len(code)} payload bytes and {len(ADDRESSES)} profile fingerprints.')

if __name__ == '__main__':
    main()
